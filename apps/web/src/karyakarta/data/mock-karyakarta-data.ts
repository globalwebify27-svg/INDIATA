export function computeKaryakartaKpiStats(
  voters: VoterRecord[],
  booths: PollingBooth[],
  issues: IssueTicket[],
  slips: VoterSlipRecord[]
): KaryakartaKpiStats {
  const totalAssignedVoters = voters.length;
  const visitedVoters = voters.filter((v) => v.isVisited).length;
  const unvisitedVoters = totalAssignedVoters - visitedVoters;
  const surveysCompleted = voters.filter((v) => !!(v.remarks || v.demand || v.scheme)).length;
  const importantVoters = voters.filter((v) => v.isImportant).length;
  const favouriteVoters = voters.filter((v) => v.isFavourite).length;
  const mobileAvailable = voters.filter((v) => !!v.phone).length;
  const mobileMissing = totalAssignedVoters - mobileAvailable;
  const supportersCount = voters.filter((v) => v.classification === "Supporter").length;
  const doubtfulCount = voters.filter((v) => v.classification === "Doubtful").length;
  const opponentsCount = voters.filter((v) => v.classification === "Opponent").length;
  const neutralCount = voters.filter((v) => v.classification === "Neutral").length;
  const openIssues = issues.filter((i) => i.status !== "RESOLVED" && i.status !== "CLOSED").length;
  const resolvedIssues = issues.filter((i) => i.status === "RESOLVED" || i.status === "CLOSED").length;
  const slipsGenerated = slips.length;
  const slipsPrinted = slips.filter((s) => s.deliveryMethod === "PRINTED").length;
  const digitalSlipsSent = slips.filter((s) => s.deliveryMethod === "DIGITAL_WHATSAPP").length;
  const assignedBoothsCount = booths.length;
  const visitPercentage = totalAssignedVoters > 0 ? Math.round((visitedVoters / totalAssignedVoters) * 100) : 0;
  const surveyPercentage = totalAssignedVoters > 0 ? Math.round((surveysCompleted / totalAssignedVoters) * 100) : 0;

  return {
    totalAssignedVoters,
    visitedVoters,
    unvisitedVoters,
    surveysCompleted,
    importantVoters,
    favouriteVoters,
    mobileAvailable,
    mobileMissing,
    supportersCount,
    doubtfulCount,
    opponentsCount,
    neutralCount,
    openIssues,
    resolvedIssues,
    slipsGenerated,
    slipsPrinted,
    digitalSlipsSent,
    assignedBoothsCount,
    visitPercentage,
    surveyPercentage,
  };
}

